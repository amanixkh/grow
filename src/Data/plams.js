export function getLocalizedPalm(palm, lang) {
  const translation = PALM_TRANSLATIONS[lang]?.[palm.id]
  if (!translation) return palm

  const regions = REGION_TRANSLATIONS[lang]
  return {
    ...palm,
    ...translation,
    areas: palm.areas.map((area) => regions?.[area] ?? area),
  }
}


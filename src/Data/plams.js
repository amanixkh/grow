export function getLocalizedProvince(province, lang) {
  return province.name[lang] ?? province.name.en
}

export function palmMatchesProvince(palm, provinceId) {
  return PALM_PROVINCES[palm.id]?.includes(provinceId) ?? false
}

export function palmMatchesProvinceQuery(palm, query) {
  const provinceIds = PALM_PROVINCES[palm.id] ?? []
  return provinceIds.some((provinceId) => {
    const province = PROVINCES.find((item) => item.id === provinceId)
    return Object.values(province?.name ?? {}).some((name) => name.toLowerCase().includes(query))
  })
}

